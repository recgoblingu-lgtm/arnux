const fs = require('fs');
const path = require('path');
const root = path.join(process.cwd(), 'apps');
const entries = [];
for (const dir of fs.readdirSync(root, {withFileTypes:true})) {
  if (!dir.isDirectory() || dir.name.startsWith('.')) continue;
  const file = path.join(root, dir.name, 'manifest.js');
  if (!fs.existsSync(file)) continue;
  const source = fs.readFileSync(file, 'utf8');
  const get = (key, fallback='') => { const m = source.match(new RegExp(`${key}\\s*:\\s*['"]([^'"]*)['"]`)); return m ? m[1] : fallback; };
  const list = key => { const m=source.match(new RegExp(`${key}\\s*:\\s*\\[([^\\]]*)\\]`)); return m ? [...m[1].matchAll(/['"]([^'"]+)['"]/g)].map(x=>x[1]) : []; };
  entries.push({id:get('id',dir.name),name:get('name',dir.name),version:get('version','1.0.0'),icon:get('icon','◆'),color:get('color','#5778ff'),description:get('description','Arnux app'),permissions:list('permissions'),dependencies:list('dependencies'),changelog:list('changelog'),path:`apps/${dir.name}`});
}
entries.sort((a,b)=>a.name.localeCompare(b.name));
const output=`/* Generated by scripts/build-app-catalog.js. Do not edit by hand. */\nwindow.ARNYX_APP_CATALOG = ${JSON.stringify(entries,null,2)};\n`;
fs.writeFileSync(path.join(root,'catalog.js'),output);
console.log(`Built catalog with ${entries.length} app(s).`);
